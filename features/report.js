// /report -> Staff only: generate sales and revenue report for today or all-time
const { EmbedBuilder, SlashCommandBuilder } = require('discord.js');
const { COLOR, CURRENCY } = require('../config');
const { data, formatPeso } = require('../core/data');
const { EPHEMERAL, isStaff } = require('../core/helpers');

const commands = [
  new SlashCommandBuilder()
    .setName('report')
    .setDescription('Staff only: generate a sales and revenue report')
    .addStringOption((o) =>
      o
        .setName('timeframe')
        .setDescription('Report period')
        .setRequired(false)
        .addChoices(
          { name: 'Today (Last 24 Hours)', value: 'today' },
          { name: 'Last 7 Days', value: 'week' },
          { name: 'All Time', value: 'all' }
        )
    ),
];

async function handle(interaction) {
  if (!interaction.isChatInputCommand() || interaction.commandName !== 'report') {
    return false;
  }

  if (!isStaff(interaction.member)) {
    await interaction.reply({
      content: 'Only staff can view sales reports.',
      flags: EPHEMERAL,
    });
    return true;
  }

  const timeframe = interaction.options.getString('timeframe') || 'today';
  const now = Date.now();
  let cutoff = 0;
  let titleTimeframe = 'All Time';

  if (timeframe === 'today') {
    cutoff = now - 24 * 60 * 60 * 1000;
    titleTimeframe = 'Last 24 Hours';
  } else if (timeframe === 'week') {
    cutoff = now - 7 * 24 * 60 * 60 * 1000;
    titleTimeframe = 'Last 7 Days';
  }

  const orders = (data.ordersLog || []).filter((o) => (o.completedAt || 0) >= cutoff);

  let totalRevenue = 0;
  let totalRobux = 0;
  let robuxOrders = 0;
  let gameOrders = 0;
  const packageCounts = {};

  for (const o of orders) {
    totalRevenue += Number(o.price) || 0;
    if (o.type === 'robux' || !o.type) {
      robuxOrders++;
      totalRobux += Number(o.amount) || 0;
    } else {
      gameOrders++;
      const pkgKey = `${o.gameName || 'Game'} - ${o.label || 'Pkg'}`;
      packageCounts[pkgKey] = (packageCounts[pkgKey] || 0) + 1;
    }
  }

  // Top selling packages
  const topPackages = Object.entries(packageCounts)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 5)
    .map(([pkg, count]) => `• **${pkg}**: \`${count}\` sold`);

  // Customer ratings during period
  const periodRatings = (data.ratings || []).filter((r) => (r.timestamp || 0) >= cutoff);
  const totalRatingPoints = periodRatings.reduce((sum, r) => sum + (Number(r.rating) || 5), 0);
  const avgRating = periodRatings.length > 0 ? (totalRatingPoints / periodRatings.length).toFixed(1) : null;

  const embed = new EmbedBuilder()
    .setColor(COLOR)
    .setTitle(`📊  Revéux Sales Report — ${titleTimeframe}`)
    .setDescription(`Summary of confirmed orders delivered during this period.`)
    .addFields(
      {
        name: '💰 Total Revenue',
        value: `\`\`\`${formatPeso(totalRevenue)}\`\`\``,
        inline: true,
      },
      {
        name: '📦 Completed Orders',
        value: `\`\`\`${orders.length} orders\`\`\``,
        inline: true,
      },
      {
        name: '⭐ Customer Satisfaction',
        value: avgRating
          ? `\`\`\`${avgRating} / 5.0 ⭐ (${periodRatings.length} reviews)\`\`\``
          : '```No ratings yet```',
        inline: true,
      },
      {
        name: '💎 Robux Delivered',
        value: `\`\`\`${totalRobux.toLocaleString()} R$\`\`\``,
        inline: true,
      },
      {
        name: 'Breakdown',
        value: `• **Robux Orders:** \`${robuxOrders}\`\n• **Game Credit Orders:** \`${gameOrders}\``,
        inline: true,
      },
      {
        name: '🏆 Top Game Packages',
        value: topPackages.length > 0 ? topPackages.join('\n') : 'No game packages sold in this timeframe',
        inline: true,
      }
    )
    .setFooter({ text: `Generated by @${interaction.user.username} • Reveux Financials` })
    .setTimestamp();

  await interaction.reply({ embeds: [embed] });
  return true;
}

module.exports = { commands, handle };

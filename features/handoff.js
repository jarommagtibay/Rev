// /handoff -> Staff only: one-click AI ticket summary for mid-shift staff handoffs
const { EmbedBuilder, SlashCommandBuilder } = require('discord.js');
const { COLOR } = require('../config');
const { data } = require('../core/data');
const { EPHEMERAL, isStaff } = require('../core/helpers');
const { stageFromEmbed, isPaid } = require('../core/ticket');
const { summarizeTicketHandoff } = require('../core/ai');

const commands = [
  new SlashCommandBuilder()
    .setName('handoff')
    .setDescription('Staff only: summarize this ticket into a 4-line brief for staff handoff')
    .addBooleanOption((o) =>
      o
        .setName('public')
        .setDescription('Post the handoff brief visibly in the ticket instead of privately (default: false)')
        .setRequired(false)
    ),
];

async function runHandoff(interaction) {
  if (!isStaff(interaction.member)) {
    return interaction.reply({
      content: 'Only staff can use this command.',
      flags: EPHEMERAL,
    });
  }

  if (!(interaction.channel.topic || '').startsWith('ticket:')) {
    return interaction.reply({
      content: 'This command only works inside a ticket channel.',
      flags: EPHEMERAL,
    });
  }

  const isPublic = interaction.options.getBoolean('public') || false;
  await interaction.deferReply(isPublic ? {} : { flags: EPHEMERAL });

  const channel = interaction.channel;
  const entry = data.queue.find((e) => e.channelId === channel.id);

  // Fetch main ticket embed if available
  let stage = 'open';
  let isPaidFlag = false;
  let orderId = (entry && entry.orderId) || 'REV-XXXX';
  let productText = entry
    ? entry.type === 'game'
      ? `${entry.label} (${entry.gameName})`
      : `${(entry.amount || 0).toLocaleString()} Robux (${entry.username || '-'})`
    : channel.name;

  if (entry && entry.messageId) {
    const mainMsg = await channel.messages.fetch({ message: entry.messageId, force: true }).catch(() => null);
    if (mainMsg && mainMsg.embeds.length > 0) {
      const embed = mainMsg.embeds[0];
      stage = stageFromEmbed(embed);
      isPaidFlag = isPaid(embed);
      const idField = (embed.data?.fields || embed.fields || []).find((f) => f.name === 'Order ID');
      if (idField) orderId = idField.value.replace(/[`#]/g, '').trim();
    }
  }

  // Fetch recent messages (up to 80) for context
  const fetched = await channel.messages.fetch({ limit: 80 }).catch(() => null);
  const lines = [];
  if (fetched) {
    const sorted = [...fetched.values()].sort((a, b) => a.createdTimestamp - b.createdTimestamp);
    for (const m of sorted) {
      if (m.id === entry?.messageId) continue; // skip the main order card itself
      const content = (m.content || '').trim();
      const embedTitle = m.embeds?.[0]?.title ? `[${m.embeds[0].title}]` : '';
      const attCount = m.attachments?.size ? ` [${m.attachments.size} attachment(s)]` : '';
      const lineText = [content, embedTitle, attCount].filter(Boolean).join(' ').trim();
      if (!lineText) continue;
      lines.push(`${m.author.bot ? 'Bot' : '@' + m.author.username}: ${lineText.slice(0, 220)}`);
    }
  }

  const sticky = (data.sticky && data.sticky[channel.id]) || {};
  const result = await summarizeTicketHandoff({
    orderId,
    productText,
    price: entry?.price || 0,
    amountPaid: entry?.amountPaid || 0,
    paymentCount: (entry?.payments && entry.payments.length) || 0,
    stage,
    isPaidFlag,
    onHold: Boolean(entry?.onHold),
    stickyNote: sticky.note?.text || null,
    stickyRemind: sticky.remind?.type || null,
    lastReceipt: entry?.lastScannedReceipt || null,
    transcriptSnippet: lines.slice(-35).join('\n'),
  });

  const embed = new EmbedBuilder()
    .setColor(COLOR)
    .setTitle(`📋  Staff Handoff Brief — #${orderId}`)
    .setDescription(result.text)
    .setFooter({ text: `Generated by ${result.engine} • Requested by @${interaction.user.username}` })
    .setTimestamp();

  return interaction.editReply({ embeds: [embed] });
}

async function handle(interaction) {
  if (interaction.isChatInputCommand() && interaction.commandName === 'handoff') {
    await runHandoff(interaction);
    return true;
  }
  return false;
}

module.exports = { commands, handle };
